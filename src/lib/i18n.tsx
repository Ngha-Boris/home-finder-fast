const localeByLanguage: Record<Language, string> = { en: "en-GB", fr: "fr-FR" };

function readInitialLanguage(): Language {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "fr") return stored;
  return window.navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

function interpolate(message: string, values?: Record<string, string | number>) {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, key) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
  houseType: (type: HouseType) => string;
  formatDate: (iso: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

const fallbackI18n: I18nContextValue = {
  language: "en",
  setLanguage: () => {},
  t: (key, values) => interpolate(dictionaries.en[key], values),
  houseType: (type) => houseTypeLabels.en[type] ?? type,
  formatDate: (iso) =>
    new Date(iso).toLocaleDateString(localeByLanguage.en, {
      day: "numeric",
      month: "short",
      year: "numeric",
    }),
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readInitialLanguage);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, next);
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, values) => interpolate(dictionaries[language][key] ?? dictionaries.en[key], values),
      houseType: (type) => houseTypeLabels[language][type] ?? houseTypeLabels.en[type] ?? type,
      formatDate: (iso) =>
        new Date(iso).toLocaleDateString(localeByLanguage[language], {
          day: "numeric",
          month: "short",
          year: "numeric",
        }),
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  return value ?? fallbackI18n;
}

export function pricePresetLabel(
  preset: { min?: number | undefined; max?: number | undefined },
  language: Language,
) {
  if (language === "fr") {
    if (preset.max && !preset.min) return `Moins de ${Math.round(preset.max / 1000)}k`;
    if (preset.min && preset.max)
      return `${Math.round(preset.min / 1000)}k - ${Math.round(preset.max / 1000)}k`;
    if (preset.min && !preset.max) return `${Math.round(preset.min / 1000)}k+`;
  }
  if (preset.max && !preset.min) return `Under ${Math.round(preset.max / 1000)}k`;
  if (preset.min && preset.max)
    return `${Math.round(preset.min / 1000)}k - ${Math.round(preset.max / 1000)}k`;
  if (preset.min && !preset.max) return `${Math.round(preset.min / 1000)}k+`;
  return "";
}
